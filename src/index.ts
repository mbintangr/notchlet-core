/** Parse a declarative change plan; arrays are optional and forward references validate on the final state. */
export function parseChangePlan(input: unknown): ChangePlan {
  if (!record(input)) throw new WorkflowError('invalid_schema', 'Change plan must be a JSON object.', 'Provide a plan with intent, outcome, and authored collections.');
  exactKeys(input, ['schemaVersion', 'name', 'mode', 'intent', 'outcome', 'capabilityName', 'capabilityImpact', 'capabilityRationale', 'capabilityDelta', 'capabilitySeed', 'evidencePolicy', 'runCommand', 'previewUrl', 'readinessUrl', 'readinessExpectedStatus', 'readinessBodyContains', 'environment', 'setupCommand', 'teardownCommand', 'coveragePolicy', 'workingDirectory', 'readyTimeoutMs', 'readyIntervalMs', 'requirements', 'acceptanceScenarios', 'designDecisions', 'checks', 'tasks', 'artifactContents'], [], 'change plan');
  if (input.schemaVersion !== undefined && input.schemaVersion !== 1) throw new WorkflowError('invalid_schema', 'change plan.schemaVersion must be 1.', 'Remove schemaVersion or set it to 1.');
  const name = input.name === undefined ? undefined : stringField(input, 'name', 'change plan');
  if (input.mode !== undefined && input.mode !== 'quick' && input.mode !== 'standard') throw new WorkflowError('invalid_schema', 'change plan.mode must be quick or standard.', 'Set mode to quick or standard.');
  if (input.capabilityImpact !== undefined && input.capabilityImpact !== 'none' && input.capabilityImpact !== 'delta') throw new WorkflowError('invalid_schema', 'change plan.capabilityImpact must be none or delta.', 'Set capabilityImpact to none or delta.');
  if (input.capabilityRationale !== undefined && typeof input.capabilityRationale !== 'string') throw new WorkflowError('invalid_schema', 'change plan.capabilityRationale must be a string.', 'Provide rationale text or omit the field.');
  if (input.capabilityName !== undefined && (typeof input.capabilityName !== 'string' || !input.capabilityName.trim())) throw new WorkflowError('invalid_schema', 'change plan.capabilityName must be a non-empty string.', 'Provide a lowercase kebab-case capability name.');
  if (input.capabilitySeed !== undefined && typeof input.capabilitySeed !== 'boolean') throw new WorkflowError('invalid_schema', 'change plan.capabilitySeed must be a boolean.', 'Set capabilitySeed to true or false.');
  if (input.evidencePolicy !== undefined && input.evidencePolicy !== 'per-task' && input.evidencePolicy !== 'end-of-change') throw new WorkflowError('invalid_schema', 'change plan.evidencePolicy must be per-task or end-of-change.', 'Set evidencePolicy to per-task or end-of-change.');
  for (const key of ['runCommand', 'previewUrl', 'readinessUrl', 'readinessBodyContains', 'setupCommand', 'teardownCommand'] as const) if (input[key] !== undefined && (typeof input[key] !== 'string' || !input[key].trim())) throw new WorkflowError('invalid_schema', `change plan.${key} must be a non-empty string.`, 'Provide a non-empty string or omit the field.');
  if (input.readinessExpectedStatus !== undefined && (!Number.isInteger(input.readinessExpectedStatus) || (input.readinessExpectedStatus as number) < 100 || (input.readinessExpectedStatus as number) > 599)) throw new WorkflowError('invalid_schema', 'change plan.readinessExpectedStatus must be an HTTP status between 100 and 599.', 'Provide a valid HTTP status or omit the field.');
  if (input.coveragePolicy !== undefined && input.coveragePolicy !== 'advisory' && input.coveragePolicy !== 'strict') throw new WorkflowError('invalid_schema', 'change plan.coveragePolicy must be advisory or strict.', 'Set coveragePolicy to advisory or strict.');
  const environment = stringMap(input, 'environment', 'change plan');
  if (environment) for (const key of Object.keys(environment)) if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)) throw new WorkflowError('invalid_schema', `change plan.environment has an invalid variable name "${key}".`, 'Use environment variable names such as BASE_URL.');
  const workingDirectory = input.workingDirectory === undefined ? undefined : relativePathField(input, 'workingDirectory', 'change plan');
  const readyTimeoutMs = optionalNonNegativeInteger(input, 'readyTimeoutMs', 'change plan');
  const readyIntervalMs = optionalNonNegativeInteger(input, 'readyIntervalMs', 'change plan');
  const capabilityDelta = input.capabilityDelta === undefined ? undefined : parseCapabilityDeltaValue(input.capabilityDelta, 'change plan.capabilityDelta');
  const collection = (key: string): unknown[] => {
    if (input[key] === undefined) return [];
    if (!Array.isArray(input[key])) throw new WorkflowError('invalid_schema', `change plan.${key} must be an array.`, 'Provide an array for this collection.');
    return input[key] as unknown[];
  };
  const requirements = collection('requirements').map(parseRequirementValue);
  const acceptanceScenarios = collection('acceptanceScenarios').map(parseAcceptanceScenarioValue);
  const designDecisions = collection('designDecisions').map(parseDesignDecisionValue);
  const checks = collection('checks').map(value => {
    if (!record(value)) schemaError('change plan check must be an object.');
    exactKeys(value, ['id', 'description', 'kind', 'command', 'url', 'expectedStatus', 'expectedBodyContains', 'expectedJson', 'expectedJsonContains', 'expectedJsonAt', 'expectedHeaders', 'waitFor', 'settleMs', 'expectedSelectors', 'expectedText', 'expectedTitle', 'expectedVisibleSelectors', 'expectedHiddenSelectors', 'expectedAbsentSelectors', 'expectedEnabledSelectors', 'expectedScopedText', 'steps', 'captureArtifacts', 'expectedNoConsoleErrors', 'fullPage', 'workingDirectory', 'environment', 'requirementIds', 'scenarioIds', 'taskIds'], ['id', 'description'], 'change plan check');
    return parseCheckValue(value);
  });
  const tasks = collection('tasks').map(value => {
    if (!record(value)) schemaError('change plan task must be an object.');
    exactKeys(value, ['id', 'title', 'dependencies', 'requirementIds'], ['id', 'title'], 'change plan task');
    return parseTaskValue({ id: value.id, title: value.title, status: 'pending', dependencies: optionalUniqueStrings(value, 'dependencies', 'change plan task') ?? [], requirementIds: optionalUniqueStrings(value, 'requirementIds', 'change plan task') ?? [] });
  });
  const artifactContents: Record<string, string> = {};
  if (input.artifactContents !== undefined) {
    if (!record(input.artifactContents)) throw new WorkflowError('invalid_schema', 'change plan.artifactContents must be an object.', 'Map relative artifact paths to file contents.');
    for (const [relative, content] of Object.entries(input.artifactContents)) {
      artifactPath(path.resolve('.'), relative);
      if (PLAN_RESERVED_ARTIFACTS.has(relative)) throw new WorkflowError('invalid_plan_artifact', `Plan cannot write reserved artifact ${relative}.`, 'Use --render for proposal/spec content and reserve tasks.json, evidence.jsonl, and closure.json for Notchlet.');
      if (typeof content !== 'string') throw new WorkflowError('invalid_schema', `change plan artifact ${relative} content must be a string.`, 'Provide artifact content as a string.');
      artifactContents[relative] = content;
    }
  }
  for (const operation of capabilityDelta?.operations ?? []) {
    if (operation.operation !== 'remove' && !requirements.some(requirement => requirement.id === operation.requirementId)) {
      throw new WorkflowError('unknown_requirement', `Capability delta references unknown plan requirement ${operation.requirementId}.`, 'Add the requirement to the plan or correct the delta requirement ID.');
    }
  }
  if (input.capabilitySeed && input.capabilityImpact === 'none') throw new WorkflowError('invalid_plan_conflict', 'capabilitySeed cannot be combined with capabilityImpact none.', 'Remove capabilitySeed or declare capabilityImpact delta.');
  if (capabilityDelta?.operations.length && input.capabilityImpact === 'none') throw new WorkflowError('invalid_plan_conflict', 'Capability delta operations cannot be combined with capabilityImpact none.', 'Remove the delta operations or declare capabilityImpact delta.');
  return {
    ...(input.schemaVersion === undefined ? {} : { schemaVersion: 1 as const }),
    ...(name === undefined ? {} : { name }),
    ...(input.mode === undefined ? {} : { mode: input.mode as 'quick' | 'standard' }),
    intent: stringField(input, 'intent', 'change plan'),
    outcome: stringField(input, 'outcome', 'change plan'),
    ...(input.capabilityName === undefined ? {} : { capabilityName: input.capabilityName as string }),
    ...(input.capabilityImpact === undefined ? {} : { capabilityImpact: input.capabilityImpact as 'none' | 'delta' }),
    ...(input.capabilityRationale === undefined ? {} : { capabilityRationale: input.capabilityRationale as string }),
    ...(capabilityDelta === undefined ? {} : { capabilityDelta }),
    ...(input.capabilitySeed === undefined ? {} : { capabilitySeed: input.capabilitySeed as boolean }),
    ...(input.evidencePolicy === undefined ? {} : { evidencePolicy: input.evidencePolicy as EvidencePolicy }),
    ...(input.runCommand === undefined ? {} : { runCommand: input.runCommand as string }),
    ...(input.previewUrl === undefined ? {} : { previewUrl: input.previewUrl as string }),
    ...(input.readinessUrl === undefined ? {} : { readinessUrl: input.readinessUrl as string }),
    ...(environment === undefined ? {} : { environment }),
    ...(input.setupCommand === undefined ? {} : { setupCommand: input.setupCommand as string }),
    ...(input.teardownCommand === undefined ? {} : { teardownCommand: input.teardownCommand as string }),
    ...(input.coveragePolicy === undefined ? {} : { coveragePolicy: input.coveragePolicy as CoveragePolicy }),
    ...(workingDirectory === undefined ? {} : { workingDirectory }),
    ...(readyTimeoutMs === undefined ? {} : { readyTimeoutMs }),
    ...(readyIntervalMs === undefined ? {} : { readyIntervalMs }),
    ...(input.readinessExpectedStatus === undefined ? {} : { readinessExpectedStatus: input.readinessExpectedStatus as number }),
    ...(input.readinessBodyContains === undefined ? {} : { readinessBodyContains: input.readinessBodyContains as string }),
    requirements, acceptanceScenarios, designDecisions, checks, tasks, artifactContents,
  };
}

/** Expand a plan's capability seed and snapshot simple delta operations from authored plan content. */
export function planCapabilityDelta(plan: Pick<ChangePlan, 'requirements' | 'acceptanceScenarios' | 'capabilityDelta' | 'capabilitySeed' | 'capabilityRationale'>): CapabilityDelta | undefined {
  const operations = [...(plan.capabilityDelta?.operations ?? [])];
  if (plan.capabilitySeed) {
    const touched = new Set(operations.map(operation => operation.requirementId));
    for (const requirement of plan.requirements) {
      if (touched.has(requirement.id)) continue;
      const scenarios = plan.acceptanceScenarios.filter(scenario => scenario.requirementId === requirement.id).map(scenario => ({ ...scenario }));
      operations.push({ operation: 'add', requirementId: requirement.id, requirement: { ...requirement }, ...(scenarios.length ? { scenarios } : {}), rationale: plan.capabilityRationale?.trim() || 'Seed capability delta from the plan.' });
      touched.add(requirement.id);
    }
  }
  const snapped = operations.map(operation => {
    if (operation.operation === 'remove') return operation;
    const requirement = plan.requirements.find(item => item.id === operation.requirementId);
    const scenarios = plan.acceptanceScenarios.filter(scenario => scenario.requirementId === operation.requirementId).map(scenario => ({ ...scenario }));
    return {
      ...operation,
      ...(requirement ? { requirement: { ...requirement } } : {}),
      ...(scenarios.length ? { scenarios } : {}),
    };
  });
  return snapped.length ? { operations: snapped } : undefined;
}

/** Project a parsed plan into the change that import would produce, without touching the filesystem. */
export function projectChangePlan(name: string, plan: ChangePlan, options: { mode?: 'quick' | 'standard'; id?: string; createdAt?: string; sourcePlan?: PlanSource } = {}): { change: Change; rendered: RenderedArtifact[] } {
  const mode = options.mode ?? plan.mode ?? 'standard';
  const artifacts = Object.fromEntries([...CORE_ARTIFACTS[mode], ...Object.keys(plan.artifactContents)].map(artifact => [artifact, artifact]));
  const capabilityDelta = planCapabilityDelta(plan);
  const capabilityImpact = plan.capabilityImpact ?? (capabilityDelta?.operations.length ? 'delta' : undefined);
  const change: Change = {
    schemaVersion: CHANGE_SCHEMA_VERSION,
    id: options.id ?? stableId(name),
    name,
    createdAt: options.createdAt ?? new Date().toISOString(),
    mode,
    intent: plan.intent,
    outcome: plan.outcome,
    requirements: plan.requirements,
    acceptanceScenarios: plan.acceptanceScenarios,
    designDecisions: plan.designDecisions,
    checks: plan.checks,
    tasks: plan.tasks.map(task => ({ ...task, status: 'pending' })),
    artifacts,
    revision: 1,
    contentRevision: 1,
    ...(plan.evidencePolicy === undefined ? {} : { evidencePolicy: plan.evidencePolicy }),
    ...(plan.capabilityName === undefined ? {} : { capabilityName: plan.capabilityName }),
    ...(capabilityImpact === undefined ? {} : { capabilityImpact }),
    ...(plan.capabilityRationale === undefined ? {} : { capabilityRationale: plan.capabilityRationale }),
    ...(capabilityDelta === undefined ? {} : { capabilityDelta }),
    ...(plan.runCommand === undefined ? {} : { runCommand: plan.runCommand }),
    ...(plan.previewUrl === undefined ? {} : { previewUrl: plan.previewUrl }),
    ...(plan.readinessUrl === undefined ? {} : { readinessUrl: plan.readinessUrl }),
    ...(plan.environment === undefined ? {} : { environment: plan.environment }),
    ...(plan.setupCommand === undefined ? {} : { setupCommand: plan.setupCommand }),
    ...(plan.teardownCommand === undefined ? {} : { teardownCommand: plan.teardownCommand }),
    ...(plan.coveragePolicy === undefined ? {} : { coveragePolicy: plan.coveragePolicy }),
    ...(plan.workingDirectory === undefined ? {} : { workingDirectory: plan.workingDirectory }),
    ...(plan.readyTimeoutMs === undefined ? {} : { readyTimeoutMs: plan.readyTimeoutMs }),
    ...(plan.readyIntervalMs === undefined ? {} : { readyIntervalMs: plan.readyIntervalMs }),
    ...(plan.readinessExpectedStatus === undefined ? {} : { readinessExpectedStatus: plan.readinessExpectedStatus }),
    ...(plan.readinessBodyContains === undefined ? {} : { readinessBodyContains: plan.readinessBodyContains }),
    ...(options.sourcePlan === undefined ? {} : { sourcePlan: options.sourcePlan }),
  };
  parseChange(change);
  assertStructuralChange(change);
  return { change, rendered: renderChangeArtifacts(change) };
}

/** Apply a plan to a newly scaffolded change under one lock and one revision bump. */
export async function importChangePlan(root: string, id: string, plan: ChangePlan, options: { expectedRevision?: number; render?: boolean; markdown?: boolean; name?: string; sourcePlan?: PlanSource } = {}): Promise<{ change: Change; written: string[]; rendered: string[] }> {
  const dir = await changeDirectoryFor(root, id);
  const file = path.join(dir, 'tasks.json');
  const release = await lock(file);
  try {
    let current: Change;
    try { current = parseChange(await readFile(file, 'utf8')); }
    catch (error) { if ((error as NodeJS.ErrnoException).code === 'ENOENT') throw new WorkflowError('change_not_found', `Change not found: ${id}`, 'List changes with `notchlet change list` and use an existing change ID.'); throw error; }
    if (options.expectedRevision !== undefined && (current.revision ?? 0) !== options.expectedRevision) {
      throw new WorkflowError('revision_conflict', `Revision conflict: expected ${options.expectedRevision}, found ${current.revision ?? 0}.`, 'Reload the change with `notchlet change show`, then retry with its current revision.');
    }
    const mode = plan.mode ?? current.mode;
    const projected = projectChangePlan(current.name, plan, { mode, id: current.id, createdAt: current.createdAt, ...(options.sourcePlan === undefined ? {} : { sourcePlan: options.sourcePlan }) });
    const applied = options.markdown ? withMarkdownArtifacts(convertChange({ ...projected.change, name: options.name ?? plan.name ?? current.name }, mode)) : convertChange({ ...projected.change, name: options.name ?? plan.name ?? current.name }, mode);
    assertStructuralChange(applied);
    const next = parseChange(withExecutionSha256({ ...applied, revision: (current.revision ?? 0) + 1, contentRevision: (current.contentRevision ?? 0) + 1 }, current));
    const writes = new Map<string, string>(Object.entries(plan.artifactContents));
    if (options.render) for (const artifact of renderChangeArtifacts(next)) writes.set(artifact.path, artifact.content);
    const written: string[] = [];
    for (const [relative, content] of writes) {
      const absolute = artifactPath(dir, relative);
      let existing: string | undefined;
      try { existing = await readFile(absolute, 'utf8'); }
      catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
      if (existing === content) continue;
      await mkdir(path.dirname(absolute), { recursive: true });
      const temporary = `${absolute}.${randomUUID()}.tmp`;
      await writeFile(temporary, content, { flag: 'wx' });
      await rename(temporary, absolute);
      written.push(relative);
    }
    const temporary = `${file}.${randomUUID()}.tmp`;
    await writeFile(temporary, JSON.stringify(next, null, 2) + '\n', { flag: 'wx' });
    await rename(temporary, file);
    return { change: next, written, rendered: options.render ? renderChangeArtifacts(next).map(artifact => artifact.path) : [] };
  } finally { await release(); }
}

