/** Edit one authored item in place, preserving unrelated fields and task progress, then validate references. */
export function updateChangeItem(change: Change, kind: ChangeItemKind, id: string, patch: ChangeItemPatch): Change {
  const next = applyChangeItemPatch(change, kind, id, patch);
  assertStructuralChange(next);
  return next;
}

function appendChangeItem(change: Change, kind: ChangeItemKind, item: unknown): Change {
  if (kind === 'requirement') {
    const parsed = parseRequirement(item);
    if (change.requirements.some(current => current.id === parsed.id)) duplicate('requirement', parsed.id);
    return { ...change, requirements: [...change.requirements, parsed] };
  }
  if (kind === 'check') {
    const parsed = parseCheckValue(item as Check);
    if (change.checks.some(current => current.id === parsed.id)) duplicate('check', parsed.id);
    return { ...change, checks: [...change.checks, parsed] };
  }
  if (kind === 'scenario') {
    const parsed = parseAcceptanceScenario(item);
    if (change.acceptanceScenarios.some(current => current.id === parsed.id)) duplicate('acceptance scenario', parsed.id);
    return { ...change, acceptanceScenarios: [...change.acceptanceScenarios, parsed] };
  }
  if (kind === 'decision') {
    const parsed = parseDesignDecision(item);
    if (change.designDecisions.some(current => current.id === parsed.id)) duplicate('design decision', parsed.id);
    return { ...change, designDecisions: [...change.designDecisions, parsed] };
  }
  const parsed = parseTask(item);
  if (change.tasks.some(current => current.id === parsed.id)) duplicate('task', parsed.id);
  return { ...change, tasks: [...change.tasks, parsed] };
}

export type ChangeOperation =
  | { op: 'field'; update: ChangeFieldUpdate }
  | { op: 'add'; kind: ChangeItemKind; item: Record<string, unknown> }
  | { op: 'update'; kind: ChangeItemKind; id: string; patch: ChangeItemPatch }
  | { op: 'remove'; kind: ChangeItemKind; id: string };

const OPERATION_KIND_KEYS: Record<ChangeItemKind, string[]> = {
  requirement: ['op', 'kind', 'id', 'title', 'description'],
  check: ['op', 'kind', 'id', 'description', 'checkKind', 'command', 'url', 'expectedStatus', 'expectedBodyContains', 'expectedJson', 'expectedJsonContains', 'expectedJsonAt', 'expectedHeaders', 'waitFor', 'settleMs', 'expectedSelectors', 'expectedText', 'expectedTitle', 'expectedVisibleSelectors', 'expectedHiddenSelectors', 'expectedAbsentSelectors', 'expectedEnabledSelectors', 'expectedScopedText', 'steps', 'captureArtifacts', 'expectedNoConsoleErrors', 'fullPage', 'workingDirectory', 'environment', 'requirementIds', 'scenarioIds', 'taskIds'],
  scenario: ['op', 'kind', 'id', 'requirementId', 'when', 'then'],
  decision: ['op', 'kind', 'id', 'decision', 'rationale'],
  task: ['op', 'kind', 'id', 'title', 'dependencies', 'requirementIds'],
};

function operationPatchKeys(kind: ChangeItemKind): string[] {
  return ['op', 'kind', 'id', ...ITEM_PATCH_FIELDS[kind].filter(field => field !== 'kind'), ...(kind === 'check' ? ['checkKind'] : [])];
}

function httpStatusField(value: JsonRecord, key: string, label: string): number {
  const status = value[key];
  if (typeof status !== 'number' || !Number.isInteger(status) || status < 100 || status > 599) schemaError(`${label}.${key} must be an HTTP status between 100 and 599.`);
  return status as number;
}

function operationKind(value: unknown, label: string): ChangeItemKind {
  if (typeof value === 'string' && value in COLLECTION_FOR_KIND) return value as ChangeItemKind;
  throw new WorkflowError('invalid_schema', `${label} must be requirement, check, scenario, decision, or task.`, 'Correct the batch operation and try again.');
}

function patchFromRecord(value: JsonRecord, kind: ChangeItemKind, label: string): ChangeItemPatch {
  const patch: ChangeItemPatch = {};
  for (const field of ITEM_PATCH_FIELDS[kind]) {
    if (field === 'kind' || value[field] === undefined) continue;
    if (field === 'expectedStatus') {
      patch.expectedStatus = httpStatusField(value, field, label);
    } else if (field === 'expectedJson') {
      patch.expectedJson = optionalPlainObject(value, field, label);
    } else if (field === 'expectedJsonContains') {
      patch.expectedJsonContains = value[field];
    } else if (field === 'expectedJsonAt') {
      patch.expectedJsonAt = jsonPathAssertions(value, field, label);
    } else if (field === 'expectedHeaders') {
      patch.expectedHeaders = stringMap(value, field, label);
    } else if (field === 'settleMs') {
      patch.settleMs = optionalNonNegativeInteger(value, field, label);
    } else if (field === 'expectedNoConsoleErrors' || field === 'fullPage') {
      (patch as Record<string, unknown>)[field] = booleanField(value, field, label);
    } else if (field === 'workingDirectory') {
      patch.workingDirectory = relativePathField(value, field, label);
    } else if (field === 'environment') {
      patch.environment = stringMap(value, field, label);
    } else if (field === 'expectedScopedText') {
      patch.expectedScopedText = scopedTextExpectations(value, field, label);
    } else if (field === 'steps') {
      patch.steps = uiSteps(value, field, label);
    } else if (field === 'captureArtifacts') {
      patch.captureArtifacts = capturePolicy(value, field, label);
    } else if (field === 'title' || field === 'description' || field === 'command' || field === 'url' || field === 'expectedBodyContains' || field === 'waitFor' || field === 'expectedText' || field === 'expectedTitle' || field === 'requirementId' || field === 'when' || field === 'then' || field === 'decision' || field === 'rationale') {
      (patch as Record<string, unknown>)[field] = stringField(value, field, label);
    } else {
      const items = optionalUniqueStrings(value, field, label);
      if (items !== undefined) (patch as Record<string, unknown>)[field] = items;
    }
  }
  if (kind === 'check' && value.checkKind !== undefined) patch.kind = stringField(value, 'checkKind', label) as CheckKind;
  return patch;
}

/** Parse and validate an ordered batch authoring operation list. */
export function parseChangeOperations(value: unknown): ChangeOperation[] {
  if (!Array.isArray(value)) throw new WorkflowError('invalid_schema', 'Batch operations must be an array.', 'Provide an "operations" array in the batch file.');
  return value.map((entry, index) => {
    const label = `operations[${index}]`;
    if (!record(entry)) throw new WorkflowError('invalid_schema', `${label} must be an object.`, 'Correct the batch operation and try again.');
    if (!['field', 'add', 'update', 'remove'].includes(String(entry.op))) throw new WorkflowError('invalid_schema', `${label}.op must be field, add, update, or remove.`, 'Correct the batch operation and try again.');
    if (entry.op === 'field') {
      exactKeys(entry, ['op', 'intent', 'outcome', 'capabilityName', 'capabilityImpact', 'capabilityRationale', 'environment', 'setupCommand', 'teardownCommand', 'coveragePolicy', 'workingDirectory', 'readyTimeoutMs', 'readyIntervalMs'], ['op'], label);
      const update: ChangeFieldUpdate = {};
      if (entry.intent !== undefined) update.intent = stringField(entry, 'intent', label);
      if (entry.outcome !== undefined) update.outcome = stringField(entry, 'outcome', label);
      if (entry.capabilityName !== undefined) update.capabilityName = stringField(entry, 'capabilityName', label);
      if (entry.capabilityRationale !== undefined) update.capabilityRationale = stringField(entry, 'capabilityRationale', label);
      if (entry.environment !== undefined) update.environment = stringMap(entry, 'environment', label);
      if (entry.setupCommand !== undefined) update.setupCommand = stringField(entry, 'setupCommand', label);
      if (entry.teardownCommand !== undefined) update.teardownCommand = stringField(entry, 'teardownCommand', label);
      if (entry.workingDirectory !== undefined) update.workingDirectory = relativePathField(entry, 'workingDirectory', label);
      if (entry.readyTimeoutMs !== undefined) update.readyTimeoutMs = optionalNonNegativeInteger(entry, 'readyTimeoutMs', label);
      if (entry.readyIntervalMs !== undefined) update.readyIntervalMs = optionalNonNegativeInteger(entry, 'readyIntervalMs', label);
      if (entry.coveragePolicy !== undefined) {
        if (entry.coveragePolicy !== 'advisory' && entry.coveragePolicy !== 'strict') throw new WorkflowError('invalid_schema', `${label}.coveragePolicy must be advisory or strict.`, 'Correct the batch operation and try again.');
        update.coveragePolicy = entry.coveragePolicy;
      }
      if (entry.capabilityImpact !== undefined) {
        if (entry.capabilityImpact !== 'none' && entry.capabilityImpact !== 'delta') throw new WorkflowError('invalid_schema', `${label}.capabilityImpact must be none or delta.`, 'Correct the batch operation and try again.');
        update.capabilityImpact = entry.capabilityImpact;
      }
      if (Object.keys(update).length === 0) throw new WorkflowError('invalid_schema', `${label} must update at least one field.`, 'Correct the batch operation and try again.');
      return { op: 'field', update } as ChangeOperation;
    }
    const kind = operationKind(entry.kind, `${label}.kind`);
    if (entry.op === 'remove') {
      exactKeys(entry, ['op', 'kind', 'id'], ['op', 'kind', 'id'], label);
      return { op: 'remove', kind, id: stringField(entry, 'id', label) } as ChangeOperation;
    }
    if (entry.op === 'update') {
      exactKeys(entry, operationPatchKeys(kind), ['op', 'kind', 'id'], label);
      const patch = patchFromRecord(entry, kind, label);
      if (Object.keys(patch).length === 0) throw new WorkflowError('invalid_schema', `${label} must update at least one field.`, 'Correct the batch operation and try again.');
      return { op: 'update', kind, id: stringField(entry, 'id', label), patch } as ChangeOperation;
    }
    exactKeys(entry, OPERATION_KIND_KEYS[kind], ['op', 'kind', 'id'], label);
    const id = stringField(entry, 'id', label);
    let item: Record<string, unknown>;
    if (kind === 'requirement') item = { id, title: stringField(entry, 'title', label), description: stringField(entry, 'description', label) };
    else if (kind === 'check') item = {
      id,
      description: stringField(entry, 'description', label),
      ...(entry.checkKind === undefined ? {} : { kind: stringField(entry, 'checkKind', label) }),
      ...(entry.command === undefined ? {} : { command: stringField(entry, 'command', label) }),
      ...(entry.url === undefined ? {} : { url: stringField(entry, 'url', label) }),
      ...(entry.expectedStatus === undefined ? {} : { expectedStatus: httpStatusField(entry, 'expectedStatus', label) }),
      ...(entry.expectedBodyContains === undefined ? {} : { expectedBodyContains: stringField(entry, 'expectedBodyContains', label) }),
      ...(entry.expectedJson === undefined ? {} : { expectedJson: optionalPlainObject(entry, 'expectedJson', label) }),
      ...(entry.expectedJsonContains === undefined ? {} : { expectedJsonContains: entry.expectedJsonContains }),
      ...(entry.expectedJsonAt === undefined ? {} : { expectedJsonAt: jsonPathAssertions(entry, 'expectedJsonAt', label) }),
      ...(entry.expectedHeaders === undefined ? {} : { expectedHeaders: stringMap(entry, 'expectedHeaders', label) }),
      ...(entry.waitFor === undefined ? {} : { waitFor: stringField(entry, 'waitFor', label) }),
      ...(entry.settleMs === undefined ? {} : { settleMs: optionalNonNegativeInteger(entry, 'settleMs', label) }),
      ...(optionalUniqueStrings(entry, 'expectedSelectors', label) === undefined ? {} : { expectedSelectors: optionalUniqueStrings(entry, 'expectedSelectors', label) }),
      ...(entry.expectedText === undefined ? {} : { expectedText: stringField(entry, 'expectedText', label) }),
      ...(entry.expectedTitle === undefined ? {} : { expectedTitle: stringField(entry, 'expectedTitle', label) }),
      ...(optionalUniqueStrings(entry, 'expectedVisibleSelectors', label) === undefined ? {} : { expectedVisibleSelectors: optionalUniqueStrings(entry, 'expectedVisibleSelectors', label) }),
      ...(optionalUniqueStrings(entry, 'expectedHiddenSelectors', label) === undefined ? {} : { expectedHiddenSelectors: optionalUniqueStrings(entry, 'expectedHiddenSelectors', label) }),
      ...(optionalUniqueStrings(entry, 'expectedAbsentSelectors', label) === undefined ? {} : { expectedAbsentSelectors: optionalUniqueStrings(entry, 'expectedAbsentSelectors', label) }),
      ...(optionalUniqueStrings(entry, 'expectedEnabledSelectors', label) === undefined ? {} : { expectedEnabledSelectors: optionalUniqueStrings(entry, 'expectedEnabledSelectors', label) }),
      ...(entry.expectedScopedText === undefined ? {} : { expectedScopedText: scopedTextExpectations(entry, 'expectedScopedText', label) }),
      ...(entry.steps === undefined ? {} : { steps: uiSteps(entry, 'steps', label) }),
      ...(entry.captureArtifacts === undefined ? {} : { captureArtifacts: capturePolicy(entry, 'captureArtifacts', label) }),
      ...(entry.expectedNoConsoleErrors === undefined ? {} : { expectedNoConsoleErrors: booleanField(entry, 'expectedNoConsoleErrors', label) }),
      ...(entry.fullPage === undefined ? {} : { fullPage: booleanField(entry, 'fullPage', label) }),
      ...(entry.environment === undefined ? {} : { environment: stringMap(entry, 'environment', label) }),
      ...(entry.workingDirectory === undefined ? {} : { workingDirectory: relativePathField(entry, 'workingDirectory', label) }),
      ...(optionalUniqueStrings(entry, 'requirementIds', label) === undefined ? {} : { requirementIds: optionalUniqueStrings(entry, 'requirementIds', label) }),
      ...(optionalUniqueStrings(entry, 'scenarioIds', label) === undefined ? {} : { scenarioIds: optionalUniqueStrings(entry, 'scenarioIds', label) }),
      ...(optionalUniqueStrings(entry, 'taskIds', label) === undefined ? {} : { taskIds: optionalUniqueStrings(entry, 'taskIds', label) }),
    };
    else if (kind === 'scenario') item = { id, requirementId: stringField(entry, 'requirementId', label), when: stringField(entry, 'when', label), then: stringField(entry, 'then', label) };
    else if (kind === 'decision') item = { id, decision: stringField(entry, 'decision', label), rationale: stringField(entry, 'rationale', label) };
    else item = { id, title: stringField(entry, 'title', label), status: 'pending', dependencies: optionalUniqueStrings(entry, 'dependencies', label) ?? [], requirementIds: optionalUniqueStrings(entry, 'requirementIds', label) ?? [] };
    return { op: 'add', kind, item } as ChangeOperation;
  });
}

function applyChangeOperation(change: Change, operation: ChangeOperation): Change {
  if (operation.op === 'field') return applyChangeUpdate(change, operation.update);
  if (operation.op === 'add') return appendChangeItem(change, operation.kind, operation.item);
  if (operation.op === 'update') return applyChangeItemPatch(change, operation.kind, operation.id, operation.patch);
  return removeFromChangeValue(change, COLLECTION_FOR_KIND[operation.kind], operation.id);
}

/** Apply ordered operations in memory; structural references are checked only on the final state. */
export function applyChangeOperations(change: Change, operations: ChangeOperation[]): { change: Change; applied: number } {
  let next = change;
  for (const operation of operations) next = applyChangeOperation(next, operation);
  return { change: next, applied: operations.length };
}

/** Apply an ordered batch under one lock, validate the final structure, and bump the revision at most once. */
export async function persistChangeOperations(root: string, id: string, operations: ChangeOperation[], options: { expectedRevision?: number; refreshExecution?: boolean } = {}): Promise<{ change: Change; applied: number }> {
  const dir = await changeDirectoryFor(root, id);
  const file = path.join(dir, 'tasks.json');
  const release = await lock(file);
  try {
    let current: Change;
    try { current = parseChange(await readFile(file, 'utf8')); }
    catch (error) { if ((error as NodeJS.ErrnoException).code === 'ENOENT') throw new WorkflowError('change_not_found', `Change not found: ${id}`, 'List changes with `notchlet change list` and use an existing change ID.'); throw error; }
    if (options.expectedRevision !== undefined && (current.revision ?? 0) !== options.expectedRevision) {
      throw new WorkflowError('revision_conflict', `Revision conflict: expected ${options.expectedRevision}, found ${current.revision ?? 0}.`, 'Reload the change with `notchlet change show`, then retry with its current revision.');
    }
    const { change: applied, applied: appliedCount } = applyChangeOperations(current, operations);
    assertStructuralChange(applied);
    const next = parseChange(withExecutionSha256({ ...applied, revision: (current.revision ?? 0) + 1, contentRevision: (current.contentRevision ?? 0) + 1 }, current, options.refreshExecution));
    const temporary = `${file}.${randomUUID()}.tmp`;
    await writeFile(temporary, JSON.stringify(next, null, 2) + '\n', { flag: 'wx' });
    await rename(temporary, file);
    return { change: next, applied: appliedCount };
  } finally { await release(); }
}

