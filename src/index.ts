function duplicate(collection: string, id: string): never {
  throw new WorkflowError('duplicate_id', `A ${collection} with ID ${id} already exists.`, 'Choose a unique ID or update the existing item.');
}

export function addRequirementToChange(change: Change, requirement: Requirement): Change {
  if (change.requirements.some(item => item.id === requirement.id)) duplicate('requirement', requirement.id);
  return { ...change, requirements: [...change.requirements, parseRequirement(requirement)] };
}

export function addCheckToChange(change: Change, check: Check): Change {
  if (change.checks.some(item => item.id === check.id)) duplicate('check', check.id);
  for (const requirementId of check.requirementIds ?? []) if (!change.requirements.some(item => item.id === requirementId)) throw new WorkflowError('unknown_requirement', `Check references unknown requirement ${requirementId}.`, 'Add the requirement first or use an existing requirement ID.');
  for (const scenarioId of check.scenarioIds ?? []) if (!change.acceptanceScenarios.some(item => item.id === scenarioId)) throw new WorkflowError('unknown_scenario', `Check references unknown acceptance scenario ${scenarioId}.`, 'Add the scenario first or use an existing scenario ID.');
  for (const taskId of check.taskIds ?? []) if (!change.tasks.some(item => item.id === taskId)) throw new WorkflowError('unknown_task', `Check references unknown task ${taskId}.`, 'Add the task first or use an existing task ID.');
  return { ...change, checks: [...change.checks, parseCheckValue(check)] };
}

export function addScenarioToChange(change: Change, scenario: AcceptanceScenario): Change {
  if (!change.requirements.some(item => item.id === scenario.requirementId)) throw new WorkflowError('unknown_requirement', `Scenario references unknown requirement ${scenario.requirementId}.`, 'Add the requirement first or use an existing requirement ID.');
  if (change.acceptanceScenarios.some(item => item.id === scenario.id)) duplicate('acceptance scenario', scenario.id);
  return { ...change, acceptanceScenarios: [...change.acceptanceScenarios, parseAcceptanceScenario(scenario)] };
}

export function addDesignDecisionToChange(change: Change, decision: DesignDecision): Change {
  if (change.designDecisions.some(item => item.id === decision.id)) duplicate('design decision', decision.id);
  return { ...change, designDecisions: [...change.designDecisions, parseDesignDecision(decision)] };
}

export function addTaskToChange(change: Change, task: Task): Change {
  if (change.tasks.some(item => item.id === task.id)) duplicate('task', task.id);
  for (const requirementId of task.requirementIds) if (!change.requirements.some(item => item.id === requirementId)) throw new WorkflowError('unknown_requirement', `Task references unknown requirement ${requirementId}.`, 'Add the requirement first or use an existing requirement ID.');
  for (const dependency of task.dependencies) if (!change.tasks.some(item => item.id === dependency)) throw new WorkflowError('unknown_dependency', `Task depends on unknown task ${dependency}.`, 'Add the dependency task first or use an existing task ID.');
  return { ...change, tasks: [...change.tasks, parseTask(task)] };
}

function removeFromChangeValue(change: Change, collection: ChangeCollection, id: string): Change {
  if (collection === 'requirements') {
    const referenced = change.acceptanceScenarios.some(item => item.requirementId === id) || change.tasks.some(item => item.requirementIds.includes(id)) || change.checks.some(item => item.requirementIds?.includes(id));
    if (referenced) throw new WorkflowError('requirement_in_use', `Requirement ${id} is still referenced by a scenario, task, or check.`, 'Remove or repoint the dependent scenario, task, or check first.');
    if (!change.requirements.some(item => item.id === id)) throw new WorkflowError('item_not_found', `Requirement ${id} was not found.`, 'Inspect the change with `notchlet change show`.');
    return { ...change, requirements: change.requirements.filter(item => item.id !== id) };
  }
  if (collection === 'checks') {
    if (!change.checks.some(item => item.id === id)) throw new WorkflowError('item_not_found', `Check ${id} was not found.`, 'Inspect the change with `notchlet change show`.');
    return { ...change, checks: change.checks.filter(item => item.id !== id) };
  }
  if (collection === 'acceptanceScenarios') {
    if (!change.acceptanceScenarios.some(item => item.id === id)) throw new WorkflowError('item_not_found', `Acceptance scenario ${id} was not found.`, 'Inspect the change with `notchlet change show`.');
    return { ...change, acceptanceScenarios: change.acceptanceScenarios.filter(item => item.id !== id) };
  }
  if (collection === 'designDecisions') {
    if (!change.designDecisions.some(item => item.id === id)) throw new WorkflowError('item_not_found', `Design decision ${id} was not found.`, 'Inspect the change with `notchlet change show`.');
    return { ...change, designDecisions: change.designDecisions.filter(item => item.id !== id) };
  }
  if (!change.tasks.some(item => item.id === id)) throw new WorkflowError('item_not_found', `Task ${id} was not found.`, 'Inspect the change with `notchlet change show`.');
  const dependent = change.tasks.find(item => item.dependencies.includes(id));
  if (dependent) throw new WorkflowError('task_in_use', `Task ${id} is a dependency of ${dependent.id}.`, 'Remove the dependency first.');
  const linkedCheck = change.checks.find(item => item.taskIds?.includes(id));
  if (linkedCheck) throw new WorkflowError('task_in_use', `Task ${id} is linked by check ${linkedCheck.id}.`, 'Remove or repoint the check link first.');
  return { ...change, tasks: change.tasks.filter(item => item.id !== id) };
}

export function removeFromChange(change: Change, collection: ChangeCollection, id: string): Change {
  return removeFromChangeValue(change, collection, id);
}

