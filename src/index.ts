function scopedTextExpectations(value: JsonRecord, key: string, label: string): ScopedTextExpectation[] | undefined {
  if (value[key] === undefined) return undefined;
  if (!Array.isArray(value[key]) || (value[key] as unknown[]).length === 0) schemaError(`${label}.${key} must be a non-empty array.`);
  return (value[key] as unknown[]).map((entry, index) => {
    const entryLabel = `${label}.${key}[${index}]`;
    if (!record(entry)) schemaError(`${entryLabel} must be an object.`);
    exactKeys(entry, ['selector', 'contains'], ['selector', 'contains'], entryLabel);
    return { selector: stringField(entry, 'selector', entryLabel), contains: stringField(entry, 'contains', entryLabel) };
  });
}

function uiSteps(value: JsonRecord, key: string, label: string): UiStep[] | undefined {
  if (value[key] === undefined) return undefined;
  if (!Array.isArray(value[key]) || (value[key] as unknown[]).length === 0) schemaError(`${label}.${key} must be a non-empty array.`);
  if ((value[key] as unknown[]).length > 25) schemaError(`${label}.${key} must declare at most 25 steps.`);
  return (value[key] as unknown[]).map((entry, index) => {
    const entryLabel = `${label}.${key}[${index}]`;
    if (!record(entry)) schemaError(`${entryLabel} must be an object.`);
    exactKeys(entry, ['action', 'selector', 'value', 'key', 'text', 'contains', 'timeoutMs', 'ms'], ['action'], entryLabel);
    const action = stringField(entry, 'action', entryLabel) as UiStepAction;
    if (!UI_STEP_ACTIONS.includes(action)) schemaError(`${entryLabel}.action must be one of ${UI_STEP_ACTIONS.join(', ')}.`);
    const allowedFields = UI_STEP_FIELDS[action];
    for (const [field, fieldValue] of Object.entries(entry)) {
      if (field === 'action' || fieldValue === undefined) continue;
      if (!allowedFields.includes(field)) throw new WorkflowError('invalid_step_field', `${entryLabel}.${field} is not valid for ${action}.`, `Use only these fields for ${action}: ${allowedFields.join(', ') || '(none)'}.`);
    }
    const selector = entry.selector === undefined ? undefined : stringField(entry, 'selector', entryLabel);
    const timeoutMs = entry.timeoutMs === undefined ? undefined : optionalNonNegativeInteger(entry, 'timeoutMs', entryLabel);
    const ms = entry.ms === undefined ? undefined : optionalNonNegativeInteger(entry, 'ms', entryLabel);
    const step: UiStep = { action };
    if (['fill', 'click', 'select', 'press', 'waitFor', 'waitForVisible'].includes(action)) {
      if (selector === undefined) schemaError(`${entryLabel}.selector is required for ${action}.`);
      step.selector = selector;
    }
    if (action === 'fill' || action === 'select') {
      if (entry.value === undefined) schemaError(`${entryLabel}.value is required for ${action}.`);
      step.value = textField(entry, 'value', entryLabel);
    }
    if (action === 'press') {
      if (entry.key === undefined) schemaError(`${entryLabel}.key is required for press.`);
      step.key = stringField(entry, 'key', entryLabel);
    }
    if (action === 'assertText' || action === 'waitForText') {
      if (entry.text === undefined) schemaError(`${entryLabel}.text is required for ${action}.`);
      step.text = stringField(entry, 'text', entryLabel);
      if (selector !== undefined) step.selector = selector;
    }
    if (action === 'assertUrl') {
      if (entry.contains === undefined) schemaError(`${entryLabel}.contains is required for assertUrl.`);
      step.contains = stringField(entry, 'contains', entryLabel);
    }
    if (action === 'settle') {
      if (ms === undefined) schemaError(`${entryLabel}.ms is required for settle.`);
      step.ms = ms;
    } else if (timeoutMs !== undefined && ['waitFor', 'waitForVisible', 'waitForText', 'assertText'].includes(action)) {
      step.timeoutMs = timeoutMs;
    }
    return step;
  });
}

