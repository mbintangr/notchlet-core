function archivedInstructions(change: Change, context: InstructionContext): string {
  const archived = context.archived ?? {};
  const completed = change.tasks.filter(task => task.status === 'completed').length;
  return [
    `# Instructions: ${change.name} (archived review)`,
    '',
    `Change: ${change.id} (revision ${change.revision ?? 0}, mode ${change.mode})`,
    '',
    '## Intent',
    '',
    change.intent.trim() || '_(not authored)_',
    '',
    '## Outcome',
    '',
    change.outcome.trim() || '_(not authored)_',
    '',
    '## Archived review',
    '',
    `- Closed at: ${archived.closedAt ?? '(no closure manifest)'}`,
    `- Capability contribution: ${archived.contribution ?? '(unknown)'}`,
    `- Resulting capability revision: ${archived.resultingRevision === undefined ? '(none)' : archived.resultingRevision}`,
    `- Verification at close: ${archived.verificationStatus ?? '(unknown)'}`,
    `- Closure manifest: ${archived.manifestPath ?? `.notchlet/archive/${change.id}/closure.json`}`,
    `- Tasks completed: ${completed}/${change.tasks.length}`,
    '',
    '## Next actions',
    '',
    `- Review the manifest: \`notchlet change export ${change.id} --format json\``,
    `- Return this change to the active workspace only when follow-up work is intended: \`notchlet change restore ${change.id}\``,
    '- Do not edit archived change files in place.',
    '',
    '## Verification',
    '',
    ...(change.checks.length ? change.checks.map(check => `- ${check.id}: ${check.description}`) : ['- (none declared)']),
    '',
  ].join('\n');
}

export function instructions(change: Change, action: WorkflowAction = 'resume', context: InstructionContext = {}): string {
  if (context.archived) return archivedInstructions(change, context);
  const rollupContext: ValidationContext = context.rollup ? { rollup: true } : {};
  const state = evaluateState(change, context.verification, {}, context.closure, rollupContext);
  const eligible = state.eligibleTasks.map(id => {
    const task = change.tasks.find(item => item.id === id)!;
    return `- ${task.id}: ${task.title}${task.requirementIds.length ? ` (${task.requirementIds.join(', ')})` : ''}${task.dependencies.length ? ` after ${task.dependencies.join(', ')}` : ''}`;
  });
  const allTasks = change.tasks.length
    ? change.tasks.map(task => `- [${task.status === 'completed' ? 'x' : ' '}] ${task.id}: ${task.title}`)
    : ['- (none authored)'];
  const checks = change.checks.length
    ? change.checks.map(check => {
      const kind = check.kind ?? (check.command ? 'command' : check.url ? (check.expectedBodyContains || check.expectedJson ? 'http' : 'browser') : 'manual');
      const details = [
        ...(kind === 'command' && check.command ? [`Command: \`${check.command}\``] : []),
        ...(check.url ? [`URL: ${check.url} (expect HTTP ${check.expectedStatus ?? 200})`] : []),
        ...(check.expectedBodyContains ? [`Body contains: ${check.expectedBodyContains}`] : []),
        ...(check.expectedJson ? [`JSON subset: \`${JSON.stringify(check.expectedJson)}\``] : []),
        ...(check.expectedJsonContains === undefined ? [] : [`JSON contains: \`${JSON.stringify(check.expectedJsonContains)}\``]),
        ...(check.expectedJsonAt?.length ? [`JSON paths: ${check.expectedJsonAt.map(assertion => `${assertion.path}${assertion.equals === undefined ? '' : ` = ${JSON.stringify(assertion.equals)}`}${assertion.gte === undefined ? '' : ` >= ${assertion.gte}`}${assertion.lte === undefined ? '' : ` <= ${assertion.lte}`}${assertion.matches === undefined ? '' : ` ~ /${assertion.matches}/`}`).join('; ')}`] : []),
        ...(check.expectedHeaders ? [`Headers: ${Object.entries(check.expectedHeaders).map(([header, headerValue]) => `${header}: ${headerValue}`).join('; ')}`] : []),
        ...(check.scenarioIds?.length ? [`Scenarios: ${check.scenarioIds.join(', ')}`] : []),
        ...(check.requirementIds?.length ? [`Requirements: ${check.requirementIds.join(', ')}`] : []),
        ...(check.workingDirectory ?? change.workingDirectory ? [`Working directory: ${check.workingDirectory ?? change.workingDirectory}`] : []),
        ...(kind === 'manual' ? ['Manual check: record evidence after reviewing it.'] : []),
      ];
      return `- ${check.id} [${kind}]: ${check.description}${details.length ? `\n${details.map(detail => `  - ${detail}`).join('\n')}` : ''}`;
    })
    : ['- (none authored; closure requires at least one check)'];
  const artifacts = context.artifacts?.length
    ? context.artifacts.map(artifact => `- ${artifact.artifact} [${artifact.role}]: ${artifact.status} (${artifact.path})`)
    : ['- (no model-derived artifacts evaluated)'];
  const artifactRecovery = context.artifacts?.some(artifact => artifact.status !== 'current')
    ? `notchlet change render ${change.id} --write${context.artifacts.some(artifact => artifact.status === 'unmarked') ? ' --force' : ''}`
    : undefined;
  const affected = [...new Set([
    ...(context.verification?.missing ?? []),
    ...(context.verification?.failed ?? []),
    ...(context.verification?.stale ?? []),
    ...(context.verification?.unknown ?? []),
  ])];
  const verifyCommand = change.checks.length
    ? `notchlet verify ${change.id}${affected.length ? ` --check ${affected.join(',')}` : ''} --record`
    : undefined;
  const coverage = coverageReport(change);
  const coverageIncomplete = !coverage.complete;
  const warning = affected.length
    ? `Evidence attention required for: ${affected.join(', ')}. Run \`${verifyCommand}\` before completing tasks or closing.`
    : change.checks.length
      ? 'No missing, failed, stale, or unknown checks were reported.'
      : 'Verification is not applicable until checks are declared; planning readiness and closure remain blocked.';
  const closureBlockers = context.closure?.blockers ?? [];
  const closureSummary = context.closure === undefined
    ? 'not evaluated by this instruction context'
    : context.closure.ready ? 'ready' : `blocked (${closureBlockers.length} blocker(s))`;
  const closureActions = closureBlockers.map(blocker => `${blocker.code}: ${blocker.recovery}`);
  const guidance: Record<WorkflowAction, string[]> = {
    plan: [
      'Clarify intent and measurable outcome, complete requirements and checks, add requirement-linked acceptance scenarios and substantive design decisions where required, then validate readiness.',
      `Run \`notchlet validate ${change.id}\` and resolve every planning blocker before implementation.`,
      ...(closureActions.length ? ['Closure-relevant setup:', ...closureActions] : []),
    ],
    revise: [
      'Revise only the blocked or outdated planning material and declared artifacts. Preserve completed and in-progress task statuses.',
      artifactRecovery ? `Refresh generated artifacts with \`${artifactRecovery}\`, then run \`notchlet validate ${change.id}\`.` : `Run \`notchlet validate ${change.id}\` after edits.`,
      ...(closureActions.length ? ['Closure-relevant setup:', ...closureActions] : []),
    ],
    implement: [
      `Implement only dependency-eligible tasks (${state.eligibleTasks.join(', ') || 'none'}).`,
      ...(eligible.length ? eligible : ['- (no dependency-eligible tasks)']),
      'Start each task with `notchlet task start <task-id> --change ' + change.id + '`, then complete it with `notchlet task complete <task-id> --change ' + change.id + ' --require-evidence` after verification.',
      ...(closureActions.length ? ['Close readiness blockers:', ...closureActions] : []),
    ],
    verify: [
      `Run the declared checks and record outcomes: \`${verifyCommand ?? `notchlet verify ${change.id} --record`}\`.`,
      ...checks,
      warning,
      ...(change.runCommand ? [`Prefer \`notchlet verify ${change.id} --serve --record\` so readiness, startup output, and shutdown are captured with the evidence.`] : []),
      ...(change.setupCommand || change.teardownCommand ? ['Setup and teardown commands run around the check batch; keep them idempotent so a failed run can be retried.'] : []),
      'Checks that depend on mutable application state should isolate it (temporary data directories or a seeded fixture) or assert a contract with expectedJsonContains/expectedJsonAt instead of exact mutable counters.',
      ...(coverageIncomplete ? ['Coverage is advisory: link uncovered requirements and scenarios with --requirement/--scenario or set coveragePolicy strict to make this blocking.'] : []),
      ...(closureActions.length ? ['Close readiness blockers:', ...closureActions] : []),
    ],
    resume: [
      `Continue from current progress. Eligible tasks: ${state.eligibleTasks.join(', ') || 'none'}.`,
      'Inspect planning blockers, artifact status, and evidence before choosing start, verify, render, or close.',
      ...(closureSummary === 'ready' ? [`Close readiness is ready; preview with \`notchlet change close ${change.id} --preview\`.`] : closureActions.length ? ['Close readiness blockers:', ...closureActions] : []),
    ],
  };
  return [
    `# Instructions: ${change.name} (${action})`,
    '',
    `Change: ${change.id} (revision ${change.revision ?? 0}, mode ${change.mode})`,
    '',
    '## Intent',
    '',
    change.intent.trim() || '_(not authored)_',
    '',
    '## Outcome',
    '',
    change.outcome.trim() || '_(not authored)_',
    '',
    ...(change.runCommand || change.previewUrl || change.readinessUrl || change.environment || change.setupCommand || change.teardownCommand ? [
      '## Run and preview',
      '',
      ...(change.runCommand ? [`- Run command: \`${change.runCommand}\`${change.workingDirectory ? ` (working directory ${change.workingDirectory})` : ''}`] : []),
      ...(change.previewUrl ? [`- Preview URL: ${change.previewUrl}`] : []),
      ...(change.readinessUrl ? [`- Readiness probe: ${change.readinessUrl}${change.readyTimeoutMs ? ` (Notchlet polls for up to ${change.readyTimeoutMs}ms before HTTP checks)` : ' (declared; set readyTimeoutMs to poll automatically)'}`] : []),
      ...(change.environment ? [`- Environment: ${Object.entries(change.environment).map(([key, environmentValue]) => `${key}=${environmentValue}`).join(', ')}`] : []),
      ...(change.setupCommand ? [`- Setup command: \`${change.setupCommand}\` (runs before checks with \`verify --serve\` or always before recorded checks)`] : []),
      ...(change.teardownCommand ? [`- Teardown command: \`${change.teardownCommand}\` (always runs after checks)`] : []),
      ...(change.runCommand ? [`- Let verify own the app lifecycle: \`notchlet verify ${change.id} --serve --record\` starts the run command, waits for readiness, and stops it afterwards.`] : []),
      '',
    ] : []),
    '## Next actions',
    '',
    ...guidance[action].map(line => line.startsWith('- ') ? line : `- ${line}`),
    '',
    '## State',
    '',
    deriveState(change, rollupContext),
    '',
    `Planning blockers: ${state.planning.blockers.length ? state.planning.blockers.map(blocker => blocker.code).join(', ') : 'none'}.`,
    '',
    `Close readiness: ${closureSummary}.`,
    '',
    ...(closureBlockers.length ? [
      '## Closure blockers',
      '',
      ...closureBlockers.map(blocker => `- ${blocker.code}: ${blocker.message}\n  Recovery: ${blocker.recovery}`),
      '',
    ] : []),
    '## Tasks',
    '',
    ...allTasks,
    '',
    '## Checks',
    '',
    ...checks,
    '',
    '## Coverage',
    '',
    `Policy: ${coverage.policy}. Requirements ${coverage.requirements.covered}/${coverage.requirements.total}; scenarios ${coverage.scenarios.covered}/${coverage.scenarios.total}.`,
    ...(coverage.requirements.uncovered.length ? [`Uncovered requirements: ${coverage.requirements.uncovered.join(', ')}`] : []),
    ...(coverage.scenarios.uncovered.length ? [`Uncovered scenarios: ${coverage.scenarios.uncovered.join(', ')}`] : []),
    ...(coverage.unlinkedChecks.length ? [`Checks without requirement/scenario links: ${coverage.unlinkedChecks.join(', ')}`] : []),
    '',
    '## Artifacts',
    '',
    ...artifacts,
    '',
    ...(artifactRecovery ? [`Render command: \`${artifactRecovery}\``, ''] : []),
    '## Commands',
    '',
    `- Inspect: \`notchlet change show ${change.id}\``,
    `- Status: \`notchlet status ${change.id}\``,
    `- Validate: \`notchlet validate ${change.id}\``,
    `- Render check: \`notchlet change render ${change.id} --check\``,
    `- Render write: \`notchlet change render ${change.id} --write\``,
    `- Verify and record: \`${verifyCommand ?? `notchlet verify ${change.id} --record`}\``,
    `- Close preview: \`notchlet change close ${change.id} --preview\``,
    '',
    `Evidence: ${warning}`,
    '',
    'Engine-enforced facts are derived from declared metadata and supplied evidence; design quality and other agent judgments are not asserted as facts. Never run user commands automatically.',
    '',
  ].join('\n');
}

async function lock(file: string): Promise<() => Promise<void>> {
  const lockfile = `${file}.lock`;
  for (let attempt = 0; attempt < 40; attempt++) {
    try { await writeFile(lockfile, `${process.pid}\n`, { flag: 'wx' }); return async () => { await rm(lockfile, { force: true }); }; }
    catch (e) { if ((e as NodeJS.ErrnoException).code !== 'EEXIST') throw e; await new Promise(r => setTimeout(r, 25)); }
  }
  throw new Error('Timed out acquiring task state lock.');
}

const TASK_TRANSITIONS: Record<TaskStatus, TaskStatus[]> = {
  pending: ['in_progress'],
  in_progress: ['completed', 'pending'],
  completed: ['pending', 'in_progress'],
};

export interface TransitionOptions { force?: boolean; requireEvidence?: boolean; }
export interface TransitionWarning { code: 'evidence_missing'; taskId: string; evidenceStatus: 'stale' | 'unknown' | 'failed' | 'missing'; policy: EvidencePolicy; message: string; recovery: string; }

export async function transitionTask(file: string, taskId: string, status: TaskStatus, expectedRevision: number, options: TransitionOptions = {}): Promise<Change & { warnings?: TransitionWarning[] }> {
  const release = await lock(file);
  try {
    const current = parseChange(await readFile(file, 'utf8'));
    const revision = current.revision ?? 0;
    if (revision !== expectedRevision) throw new WorkflowError('revision_conflict', `Revision conflict: expected ${expectedRevision}, found ${revision}.`, 'Reload the change status and retry the transition with its current revision.');
    const task = current.tasks.find(t => t.id === taskId);
    if (!task) throw new WorkflowError('task_not_found', `Unknown task: ${taskId}`, 'Choose a task ID listed in the change status.');
    if (task.status === status) return current;
    if (!options.force && !TASK_TRANSITIONS[task.status].includes(status)) throw new WorkflowError('invalid_transition', `Task ${taskId} cannot move from ${task.status} to ${status}.`, task.status === 'pending' && status === 'completed' ? `Run \`notchlet task start ${taskId}\` first, then complete it.` : 'Use a supported lifecycle transition or pass --force to override.');
    if ((status === 'in_progress' || status === 'completed') && task.dependencies.some(id => current.tasks.find(t => t.id === id)?.status !== 'completed')) throw new WorkflowError('dependencies_incomplete', 'Task dependencies must be completed first.', 'Complete the task dependencies, reload status, then retry.');
    const warnings: TransitionWarning[] = [];
    if (status === 'completed' && (options.requireEvidence || current.evidencePolicy !== 'end-of-change')) {
      let evidenceStatus: Awaited<ReturnType<typeof taskEvidenceStatus>>;
      try { evidenceStatus = await taskEvidenceStatus(await workspaceRootForChangeFile(file), current, taskId); }
      catch { evidenceStatus = { taskId, status: 'missing', checkIds: [], recovery: `notchlet verify ${current.id} --record --task ${taskId}` }; }
      if (evidenceStatus.status !== 'current') {
        if (options.requireEvidence) throw new WorkflowError('evidence_required', `Task ${taskId} cannot be completed without current passed evidence; evidence is ${evidenceStatus.status}.`, evidenceStatus.recovery);
        warnings.push({
          code: 'evidence_missing',
          taskId,
          evidenceStatus: evidenceStatus.status,
          policy: current.evidencePolicy ?? 'per-task',
          message: `Task ${taskId} has no current passed evidence; evidence is ${evidenceStatus.status} under the ${current.evidencePolicy ?? 'per-task'} policy.`,
          recovery: `${evidenceStatus.recovery}; or run \`notchlet change update ${current.id} --evidence-policy end-of-change\` if one final verification batch should cover all tasks.`,
        });
      }
    }
    task.status = status;
    const next = { ...current, revision: revision + 1 };
    const temp = `${file}.${randomUUID()}.tmp`;
    await writeFile(temp, JSON.stringify(next, null, 2) + '\n', { flag: 'wx' });
    await rename(temp, file);
    return warnings.length ? { ...next, warnings } : next;
  } finally { await release(); }
}

/** Complete many tasks under one revision bump, honoring dependency order. */
export async function completeTasks(file: string, expectedRevision: number, options: TransitionOptions & { taskIds?: string[] } = {}): Promise<{ change: Change; warnings: TransitionWarning[]; completed: string[] }> {
  const release = await lock(file);
  try {
    const current = parseChange(await readFile(file, 'utf8'));
    const revision = current.revision ?? 0;
    if (revision !== expectedRevision) throw new WorkflowError('revision_conflict', `Revision conflict: expected ${expectedRevision}, found ${revision}.`, 'Reload the change status and retry with its current revision.');
    const selected = options.taskIds?.length ? new Set(options.taskIds) : null;
    if (selected) for (const id of selected) if (!current.tasks.some(task => task.id === id)) throw new WorkflowError('task_not_found', `Unknown task: ${id}`, 'Choose task IDs listed in the change status.');
    const order: string[] = [];
    const seen = new Set<string>(), visiting = new Set<string>();
    const visit = (id: string): void => {
      if (seen.has(id) || visiting.has(id)) return;
      visiting.add(id);
      const task = current.tasks.find(item => item.id === id);
      for (const dependency of task?.dependencies ?? []) visit(dependency);
      visiting.delete(id);
      seen.add(id);
      order.push(id);
    };
    for (const task of current.tasks) visit(task.id);
    const targets = order.filter(id => (selected ? selected.has(id) : true) && current.tasks.find(task => task.id === id)?.status !== 'completed');
    const completedNow = new Set(current.tasks.filter(task => task.status === 'completed').map(task => task.id));
    const warnings: TransitionWarning[] = [];
    const completed: string[] = [];
    for (const id of targets) {
      const task = current.tasks.find(item => item.id === id)!;
      const unmet = task.dependencies.filter(dependency => !completedNow.has(dependency));
      if (unmet.length) throw new WorkflowError('dependencies_incomplete', `Task ${id} has incomplete dependencies: ${unmet.join(', ')}.`, 'Complete the task dependencies, reload status, then retry.');
      if (options.requireEvidence || current.evidencePolicy !== 'end-of-change') {
        let evidenceStatus: Awaited<ReturnType<typeof taskEvidenceStatus>>;
        try { evidenceStatus = await taskEvidenceStatus(await workspaceRootForChangeFile(file), current, id); }
        catch { evidenceStatus = { taskId: id, status: 'missing', checkIds: [], recovery: `notchlet verify ${current.id} --record --task ${id}` }; }
        if (evidenceStatus.status !== 'current') {
          if (options.requireEvidence) throw new WorkflowError('evidence_required', `Task ${id} cannot be completed without current passed evidence; evidence is ${evidenceStatus.status}.`, evidenceStatus.recovery);
          warnings.push({
            code: 'evidence_missing',
            taskId: id,
            evidenceStatus: evidenceStatus.status,
            policy: current.evidencePolicy ?? 'per-task',
            message: `Task ${id} has no current passed evidence; evidence is ${evidenceStatus.status} under the ${current.evidencePolicy ?? 'per-task'} policy.`,
            recovery: `${evidenceStatus.recovery}; or run \`notchlet change update ${current.id} --evidence-policy end-of-change\` if one final verification batch should cover all tasks.`,
          });
        }
      }
      task.status = 'completed';
      completedNow.add(id);
      completed.push(id);
    }
    if (!completed.length) return { change: current, warnings, completed };
    const next = { ...current, revision: revision + 1 };
    const temp = `${file}.${randomUUID()}.tmp`;
    await writeFile(temp, JSON.stringify(next, null, 2) + '\n', { flag: 'wx' });
    await rename(temp, file);
    return { change: next, warnings, completed };
  } finally { await release(); }
}
