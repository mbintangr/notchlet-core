function stableProjection(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(stableProjection);
  if (value !== null && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value as Record<string, unknown>)
      .filter(([, entry]) => entry !== undefined)
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([key, entry]) => [key, stableProjection(entry)]));
  }
  return value;
}

export interface ExecutionDrift {
  status: 'current' | 'drifted' | 'unrecorded';
  recordedSha256?: string;
  currentSha256: string;
  recovery?: string;
}

/** Canonical hash of the metadata that controls what executes and how evidence is collected. */
export function executionSha256(change: Change): string {
  return createHash('sha256').update(JSON.stringify(stableProjection({
    runCommand: change.runCommand,
    previewUrl: change.previewUrl,
    readinessUrl: change.readinessUrl,
    readinessExpectedStatus: change.readinessExpectedStatus,
    readinessBodyContains: change.readinessBodyContains,
    environment: change.environment,
    setupCommand: change.setupCommand,
    teardownCommand: change.teardownCommand,
    workingDirectory: change.workingDirectory,
    readyTimeoutMs: change.readyTimeoutMs,
    readyIntervalMs: change.readyIntervalMs,
  }))).digest('hex');
}

/** Compare the CLI-recorded execution hash with the current metadata; legacy changes report unrecorded. */
export function inspectExecutionDrift(change: Change): ExecutionDrift {
  const currentSha256 = executionSha256(change);
  if (change.executionSha256 === undefined) return { status: 'unrecorded', currentSha256 };
  if (change.executionSha256 === currentSha256) return { status: 'current', recordedSha256: change.executionSha256, currentSha256 };
  return {
    status: 'drifted',
    recordedSha256: change.executionSha256,
    currentSha256,
    recovery: `Review the execution metadata, then re-apply it with \`notchlet change update ${change.id}\` so the revision and execution fingerprint advance together.`,
  };
}

/** Record the execution fingerprint on CLI writes; unrelated writes preserve existing state-only drift. */
function withExecutionSha256(next: Change, previous?: Change, refresh = false): Change {
  const currentSha256 = executionSha256(next);
  const previousActual = previous === undefined ? undefined : executionSha256(previous);
  const preserveDrift = !refresh
    && previous?.executionSha256 !== undefined
    && previous.executionSha256 !== previousActual
    && currentSha256 === previousActual;
  return { ...next, executionSha256: preserveDrift ? previous!.executionSha256! : currentSha256 };
}

function normalizePorts(value: string): string {
  return value
    .replace(/\b(https?:\/\/[^\s/:]+):\d+/gi, '$1:{port}')
    .replace(/\b(localhost|127\.0\.0\.1|\[::1\]):\d+\b/gi, '$1:{port}')
    .replace(/(^|\s)--port(?:=|\s+)\d+/g, '$1--port {port}')
    .replace(/(^|\s)-p\s+\d+/g, '$1-p {port}');
}

function normalizeContractUrl(value: string): string {
  try {
    const url = new URL(value);
    url.port = '';
    url.hash = '';
    return `${url.protocol}//${url.hostname}:{port}${url.pathname}${url.search}`;
  } catch {
    return normalizePorts(value);
  }
}

function normalizeContractCommand(value: string, environment: Record<string, string> | undefined): string {
  let normalized = normalizePorts(value);
  for (const [name, secret] of Object.entries(environment ?? {}).sort(([left], [right]) => left.localeCompare(right))) {
    if (secret) normalized = normalized.split(secret).join(`{env:${name}}`);
  }
  return normalized;
}

function normalizeContractEnvironment(environment: Record<string, string> | undefined): Record<string, string> | undefined {
  if (!environment) return undefined;
  return Object.fromEntries(Object.keys(environment).sort().map(name => [name, '{value}']));
}

function contractCheckKind(check: Check): CheckKind {
  return check.kind ?? (check.command ? 'command' : check.url ? (check.expectedBodyContains || check.expectedJson ? 'http' : 'browser') : 'manual');
}

/**
 * Structural contract projection: IDs, relationships, assertions, and execution shapes.
 * Prose, labels, environment values, ports, change identity, and readiness polling tuning
 * (readyTimeoutMs/readyIntervalMs) are excluded so independent runs that authored the same
 * contract compare equal.
 */
export function contractProjection(change: Change): unknown {
  const sortIds = (values: string[] | undefined) => [...(values ?? [])].sort();
  return stableProjection({
    schemaVersion: 1,
    mode: change.mode,
    requirements: [...change.requirements].map(requirement => ({ id: requirement.id })).sort((left, right) => left.id.localeCompare(right.id)),
    acceptanceScenarios: [...change.acceptanceScenarios]
      .map(scenario => ({ id: scenario.id, requirementId: scenario.requirementId }))
      .sort((left, right) => left.id.localeCompare(right.id)),
    tasks: [...change.tasks]
      .map(task => ({ id: task.id, dependencies: sortIds(task.dependencies), requirementIds: sortIds(task.requirementIds) }))
      .sort((left, right) => left.id.localeCompare(right.id)),
    checks: [...change.checks].map(check => ({
      id: check.id,
      kind: contractCheckKind(check),
      command: check.command === undefined ? undefined : normalizeContractCommand(check.command, change.environment),
      url: check.url === undefined ? undefined : normalizeContractUrl(check.url),
      expectedStatus: check.expectedStatus,
      expectedBodyContains: check.expectedBodyContains,
      expectedJson: check.expectedJson,
      expectedJsonContains: check.expectedJsonContains,
      expectedJsonAt: check.expectedJsonAt,
      expectedHeaders: check.expectedHeaders,
      waitFor: check.waitFor,
      settleMs: check.settleMs,
      expectedSelectors: check.expectedSelectors === undefined ? undefined : sortIds(check.expectedSelectors),
      expectedText: check.expectedText,
      expectedTitle: check.expectedTitle,
      expectedVisibleSelectors: check.expectedVisibleSelectors === undefined ? undefined : sortIds(check.expectedVisibleSelectors),
      expectedHiddenSelectors: check.expectedHiddenSelectors === undefined ? undefined : sortIds(check.expectedHiddenSelectors),
      expectedAbsentSelectors: check.expectedAbsentSelectors === undefined ? undefined : sortIds(check.expectedAbsentSelectors),
      expectedEnabledSelectors: check.expectedEnabledSelectors === undefined ? undefined : sortIds(check.expectedEnabledSelectors),
      expectedScopedText: check.expectedScopedText === undefined ? undefined : check.expectedScopedText
        .map(expectation => ({ selector: expectation.selector, contains: expectation.contains }))
        .sort((left, right) => `${left.selector}:${left.contains}`.localeCompare(`${right.selector}:${right.contains}`)),
      steps: check.steps,
      captureArtifacts: check.captureArtifacts,
      expectedNoConsoleErrors: check.expectedNoConsoleErrors,
      fullPage: check.fullPage,
      workingDirectory: check.workingDirectory,
      environment: normalizeContractEnvironment(check.environment),
      requirementIds: check.requirementIds === undefined ? undefined : sortIds(check.requirementIds),
      scenarioIds: check.scenarioIds === undefined ? undefined : sortIds(check.scenarioIds),
      taskIds: check.taskIds === undefined ? undefined : sortIds(check.taskIds),
    })).sort((left, right) => left.id.localeCompare(right.id)),
    capabilityImpact: change.capabilityImpact,
    capabilityDelta: change.capabilityDelta === undefined ? undefined : change.capabilityDelta.operations
      .map(operation => ({
        operation: operation.operation,
        requirementId: operation.requirementId,
        requirementIdDefinition: operation.requirement === undefined ? undefined : operation.requirement.id,
        scenarioIds: operation.scenarios === undefined ? undefined : operation.scenarios.map(scenario => scenario.id).sort(),
      }))
      .sort((left, right) => left.requirementId.localeCompare(right.requirementId)),
    coveragePolicy: change.coveragePolicy ?? 'advisory',
    evidencePolicy: change.evidencePolicy ?? 'per-task',
    runCommand: change.runCommand === undefined ? undefined : normalizeContractCommand(change.runCommand, change.environment),
    setupCommand: change.setupCommand === undefined ? undefined : normalizeContractCommand(change.setupCommand, change.environment),
    teardownCommand: change.teardownCommand === undefined ? undefined : normalizeContractCommand(change.teardownCommand, change.environment),
    previewUrl: change.previewUrl === undefined ? undefined : normalizeContractUrl(change.previewUrl),
    readinessUrl: change.readinessUrl === undefined ? undefined : normalizeContractUrl(change.readinessUrl),
    readinessExpectedStatus: change.readinessExpectedStatus,
    readinessBodyContains: change.readinessBodyContains,
    environment: normalizeContractEnvironment(change.environment),
    workingDirectory: change.workingDirectory,
    // readyTimeoutMs/readyIntervalMs are polling tuning, not behavioral contract.
  });
}

/** SHA-256 of the normalized structural contract; independent of prose, ports, environment values, identity, and readiness polling tuning. */
export function contractSha256(change: Change): string {
  return createHash('sha256').update(JSON.stringify(contractProjection(change))).digest('hex');
}

function normalizeGeneratedMarkdown(value: string): string {
  return value.split(/\r?\n/).map(line => {
    if (/^\s*-\s+Status:\s/.test(line)) return line.replace(/(-\s+Status:\s).*/, '$1{status}');
    if (/^\s*-\s+\[[ xX]\]/.test(line)) return line.replace(/\[[ xX]\]/, '[{status}]');
    if (/^\s*\d+\/\d+\s+tasks completed\.$/.test(line)) return '{progress} tasks completed.';
    return line;
  }).join('\n');
}

function normalizeGeneratedJson(value: string): string | undefined {
  try { return JSON.stringify(stableProjection(JSON.parse(value))); }
  catch { return undefined; }
}

/** Classify a rendered-artifact mismatch as authored contract drift or lifecycle-only drift. */
export function classifyArtifactDrift(rendered: RenderedArtifact, existing: string): Exclude<ArtifactDriftKind, 'none'> {
  if (rendered.role === 'canonical') {
    const existingJson = normalizeGeneratedJson(existing);
    const renderedJson = normalizeGeneratedJson(rendered.content);
    if (existingJson !== undefined && renderedJson !== undefined && existingJson === renderedJson) return 'generated-state';
    return 'authored';
  }
  return normalizeGeneratedMarkdown(existing) === normalizeGeneratedMarkdown(rendered.content) ? 'generated-state' : 'authored';
}

function jsonDocument(value: unknown): string { return `${JSON.stringify(value, null, 2)}\n`; }

function checkDetailLines(check: Check): string[] {
  const kind = check.kind ?? (check.command ? 'command' : check.url ? (check.expectedBodyContains || check.expectedJson ? 'http' : 'browser') : 'manual');
  return [
    ...(check.command ? [`  - Command: \`${check.command}\``] : []),
    ...(check.url ? [`  - URL: ${check.url} (expect HTTP ${check.expectedStatus ?? 200})`] : []),
    ...(check.expectedBodyContains ? [`  - Body contains: ${check.expectedBodyContains}`] : []),
    ...(check.expectedJson ? [`  - JSON subset: \`${JSON.stringify(check.expectedJson)}\``] : []),
    ...(check.workingDirectory ? [`  - Working directory: ${check.workingDirectory}`] : []),
    ...(kind === 'manual' ? ['  - Manual check: record evidence after reviewing it.'] : []),
  ];
}

function renderProposal(doc: ProposalDocument): string {
  const requirementLines = doc.requirements.length
    ? doc.requirements.map(requirement => `- **${requirement.id}** ${requirement.title}: ${requirement.description}`)
    : ['_(no requirements authored)_'];
  const scenarioLines = doc.acceptanceScenarios.length
    ? doc.acceptanceScenarios.map(scenario => `- **${scenario.id}** (${scenario.requirementId}) WHEN ${scenario.when} THEN ${scenario.then}`)
    : ['_(no acceptance scenarios authored)_'];
  const taskLines = doc.tasks.length
    ? doc.tasks.map(task => `- **${task.id}** ${task.title}${task.dependencies.length ? ` (depends on ${task.dependencies.join(', ')})` : ''}${task.requirementIds.length ? ` (${task.requirementIds.join(', ')})` : ''}`)
    : ['_(no tasks authored)_'];
  const approachLines = doc.designDecisions.length
    ? doc.designDecisions.map(decision => `- **${decision.id}** ${sentence(decision.decision)}: ${sentence(decision.rationale)}`)
    : ['_(no approach authored in proposal.json; see the authored design artifact when declared)_'];
  const checkLines = doc.checks.length
    ? doc.checks.flatMap(check => [`- **${check.id}** ${check.description}`, ...checkDetailLines(check)])
    : ['_(no checks authored)_'];
  return [
    GENERATED_ARTIFACT_MARKER,
    '',
    `# ${doc.change.name}`,
    '',
    '## Intent',
    '',
    doc.change.intent.trim() || '_(not authored)_',
    '',
    '## Outcome',
    '',
    doc.change.outcome.trim() || '_(not authored)_',
    '',
    '## Approach',
    '',
    ...approachLines,
    '',
    '## Requirements',
    '',
    ...requirementLines,
    '',
    '## Acceptance scenarios',
    '',
    ...scenarioLines,
    '',
    '## Tasks',
    '',
    ...taskLines,
    '',
    '## Verification',
    '',
    ...checkLines,
    '',
    '## Capability',
    '',
    `- Name: ${doc.capability.name ?? '(not declared)'}`,
    `- Baseline revision: ${doc.capability.baselineRevision === undefined ? '(not captured)' : doc.capability.baselineRevision}`,
    `- Impact: ${doc.capability.impact ?? '(not declared)'}`,
    `- Rationale: ${doc.capability.rationale?.trim() || '(none)'}`,
    `- Delta operations: ${doc.capability.deltaOperations.length}`,
    ...doc.capability.deltaOperations.map(operation => `  - ${operation.operation} ${operation.requirementId}: ${operation.rationale}`),
    '',
  ].join('\n');
}

function renderSpecification(doc: SpecificationDocument): string {
  const lines: string[] = [GENERATED_ARTIFACT_MARKER, '', `# ${doc.change.name} specification`, '', '## Requirements and acceptance scenarios', ''];
  if (!doc.requirements.length) lines.push('_(no requirements authored)_', '');
  for (const requirement of doc.requirements) {
    lines.push(`### ${requirement.id}: ${requirement.title}`, '', requirement.description, '');
    if (!requirement.scenarios.length) lines.push('_(no acceptance scenarios)_', '');
    for (const scenario of requirement.scenarios) lines.push(`- **${scenario.id}** WHEN ${scenario.when} THEN ${scenario.then}`);
    if (requirement.scenarios.length) lines.push('');
    lines.push('Linked tasks:', ...(requirement.taskIds.length ? requirement.taskIds.map(id => `- ${id}`) : ['- _(none)_']), '');
    lines.push('Linked checks:', ...(requirement.checkIds.length ? requirement.checkIds.map(id => `- ${id}`) : ['- _(none)_']), '');
  }
  return `${lines.join('\n')}\n`;
}

function renderTasks(change: Change): string {
  const completed = change.tasks.filter(task => task.status === 'completed').length;
  const taskLines = change.tasks.length
    ? change.tasks.map(task => [
      `- [${task.status === 'completed' ? 'x' : ' '}] **${task.id}** ${task.title}`,
      `  - Status: ${task.status}`,
      `  - Requirements: ${task.requirementIds.length ? task.requirementIds.join(', ') : '(none)'}`,
      `  - Depends on: ${task.dependencies.length ? task.dependencies.join(', ') : '(none)'}`,
    ].join('\n'))
    : ['_(no tasks authored)_'];
  const dependencies = change.tasks.flatMap(task => task.dependencies.map(dependency => `- ${task.id} depends on ${dependency}`));
  const checkLines = change.checks.length
    ? change.checks.map(check => [`- **${check.id}** ${check.description}`, ...checkDetailLines(check), `  - Tasks: ${check.taskIds?.length ? check.taskIds.join(', ') : '(none)'}`].join('\n'))
    : ['_(no checks authored)_'];
  return [
    GENERATED_ARTIFACT_MARKER,
    '',
    `# ${change.name} tasks`,
    '',
    '## Progress',
    '',
    `${completed}/${change.tasks.length} tasks completed.`,
    '',
    '## Tasks',
    '',
    ...taskLines,
    '',
    '## Dependencies',
    '',
    ...(dependencies.length ? dependencies : ['_(no dependencies)_']),
    '',
    '## Checks',
    '',
    ...checkLines,
    '',
  ].join('\n');
}

/** Render declared model-derived artifacts deterministically; canonical JSON is emitted before its Markdown view. */
export function renderChangeArtifacts(change: Change): RenderedArtifact[] {
  const rendered: RenderedArtifact[] = [];
  const proposal = proposalDocument(change);
  const specification = specificationDocument(change);
  const proposalJsonPath = change.artifacts?.['proposal.json'];
  if (proposalJsonPath) rendered.push({ artifact: 'proposal.json', role: 'canonical', path: proposalJsonPath, content: jsonDocument(proposal) });
  const proposalPath = change.artifacts?.['proposal.md'];
  if (proposalPath) rendered.push({ artifact: 'proposal.md', role: 'rendered', path: proposalPath, content: renderProposal(proposal) });
  const specJsonPath = change.artifacts?.['spec.json'];
  if (specJsonPath) rendered.push({ artifact: 'spec.json', role: 'canonical', path: specJsonPath, content: jsonDocument(specification) });
  const specPath = change.artifacts?.['spec.md'];
  if (specPath) rendered.push({ artifact: 'spec.md', role: 'rendered', path: specPath, content: renderSpecification(specification) });
  const tasksPath = change.artifacts?.['tasks.md'];
  if (tasksPath) rendered.push({ artifact: 'tasks.md', role: 'rendered', path: tasksPath, content: renderTasks(change) });
  return rendered;
}

function artifactPath(directory: string, relative: string): string {
  if (!relative || path.isAbsolute(relative) || relative.split(/[\\/]/).includes('..')) throw new WorkflowError('invalid_artifact_path', `Invalid artifact path: ${relative}`, 'Declare artifacts with relative paths inside the change directory.');
  return path.join(directory, relative);
}

export interface ChangeArtifactInspection { change: Change; artifacts: ArtifactStatus[]; drifted: boolean; executionDrift: ExecutionDrift; }

/** Compare declared model-derived artifacts with what the current model would render. */
export async function inspectChangeArtifacts(root: string, id: string): Promise<ChangeArtifactInspection> {
  let change: Change;
  let directory: string;
  try {
    change = await readChange(root, id);
    directory = await changeDirectoryFor(root, id);
  } catch (error) {
    if (!(error instanceof WorkflowError) || error.code !== 'change_not_found') throw error;
    change = await readArchivedChange(root, id);
    directory = (await resolveChangeLocation(root, id, { scope: 'archive' })).directory;
  }
  const artifacts: ArtifactStatus[] = [];
  const rendered = renderChangeArtifacts(change);
  for (const item of rendered) {
    let existing: string | undefined;
    try { existing = await readFile(artifactPath(directory, item.path), 'utf8'); }
    catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
    const status: ArtifactStatusValue = existing === undefined ? 'missing' : existing === item.content ? 'current' : item.role === 'canonical' || existing.includes(GENERATED_ARTIFACT_MARKER) ? 'drifted' : 'unmarked';
    const drift: ArtifactDriftKind = status === 'drifted' ? classifyArtifactDrift(item, existing!) : 'none';
    artifacts.push({ artifact: item.artifact, path: item.path, role: item.role, status, drift });
  }
  const renderedKeys = new Set(rendered.map(item => item.artifact));
  for (const [artifact, relative] of Object.entries(change.artifacts).sort(([left], [right]) => left.localeCompare(right))) {
    if (renderedKeys.has(artifact as RenderedArtifactName)) continue;
    let present = false;
    try { await access(artifactPath(directory, relative)); present = true; }
    catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
    artifacts.push({ artifact, path: relative, role: artifactRole(artifact), status: present ? 'present' : 'missing', drift: 'none' });
  }
  return { change, artifacts, drifted: rendered.some(item => artifacts.find(artifact => artifact.artifact === item.artifact)?.status !== 'current'), executionDrift: inspectExecutionDrift(change) };
}

/** Detect common artifact-placement mistakes, such as authoring design.md at the project root. */
export async function diagnoseArtifactLocations(root: string, id: string, change: Change): Promise<Issue[]> {
  const issues: Issue[] = [];
  const location = await resolveChangeLocation(root, id, { scope: 'merged' });
  const directory = location.directory;
  for (const [artifact, relative] of Object.entries(change.artifacts)) {
    const target = artifactPath(directory, relative);
    try { await access(target); continue; }
    catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
    const misplaced = path.join(path.resolve(root), path.basename(relative));
    try {
      await access(misplaced);
      issues.push({
        code: 'misplaced_artifact',
        message: `${artifact} is declared at ${relative} but the change file is missing; a same-named file exists at the workspace root instead.`,
        recovery: `Move ${path.basename(relative)} to .notchlet/changes/${location.relativePath}/${relative}, then run \`notchlet validate ${location.relativePath}\`.`,
      });
    } catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
  }
  return issues;
}

export interface ArtifactWriteResult { change: Change; written: string[]; unchanged: string[]; refused: Array<{ artifact: string; path: string; reason: string }>; }

/** Write rendered artifacts atomically and bump the revision once when anything changed. */
export async function writeChangeArtifacts(root: string, id: string, options: { force?: boolean; markdown?: boolean } = {}): Promise<ArtifactWriteResult> {
  const dir = await changeDirectoryFor(root, id);
  const file = path.join(dir, 'tasks.json');
  const release = await lock(file);
  try {
    let current: Change;
    try { current = parseChange(await readFile(file, 'utf8')); }
    catch (error) { if ((error as NodeJS.ErrnoException).code === 'ENOENT') throw new WorkflowError('change_not_found', `Change not found: ${id}`, 'List changes with `notchlet change list` and use an existing change ID.'); throw error; }
    const model = options.markdown ? withMarkdownArtifacts(current) : current;
    const declarationChanged = Object.keys(model.artifacts).length !== Object.keys(current.artifacts).length;
    const written: string[] = [], unchanged: string[] = [], refused: ArtifactWriteResult['refused'] = [];
    for (const rendered of renderChangeArtifacts(model)) {
      const absolute = artifactPath(dir, rendered.path);
      let existing: string | undefined;
      try { existing = await readFile(absolute, 'utf8'); }
      catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
      if (existing === rendered.content) { unchanged.push(rendered.artifact); continue; }
      if (existing !== undefined && rendered.role !== 'canonical' && !existing.includes(GENERATED_ARTIFACT_MARKER) && !options.force) {
        refused.push({ artifact: rendered.artifact, path: rendered.path, reason: 'existing artifact lacks the generated-content marker; pass --force to overwrite hand-authored content' });
        continue;
      }
      await mkdir(path.dirname(absolute), { recursive: true });
      const temporary = `${absolute}.${randomUUID()}.tmp`;
      await writeFile(temporary, rendered.content, { flag: 'wx' });
      await rename(temporary, absolute);
      written.push(rendered.artifact);
    }
    if (!written.length && !declarationChanged) return { change: current, written, unchanged, refused };
    // Generated views are derived from the model; rendering progress must not advance contentRevision.
    const next = parseChange({ ...model, revision: (current.revision ?? 0) + 1 });
    const temporary = `${file}.${randomUUID()}.tmp`;
    await writeFile(temporary, JSON.stringify(next, null, 2) + '\n', { flag: 'wx' });
    await rename(temporary, file);
    return { change: next, written, unchanged, refused };
  } finally { await release(); }
}

